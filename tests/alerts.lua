local count = 0
local function check(value, message)
    count = count + 1
    assert(value, message)
end
local function member(key, hp, max)
    return { key = key, name = key, hp = hp, max = max or 100, known = hp ~= nil, actor = { key = key } }
end
local tracker = __alerts.new({ AlertDuration = 2, MaxAlerts = 3 })
check(#tracker:update({member('A',100)},0) == 0, 'loaded squad establishes silent baseline')
local events = tracker:update({member('A',100),member('B',100)},1)
check(#events == 1 and events[1].kind == 'joined' and events[1].name == 'B', 'new member joins once')
check(#tracker:update({member('A',100),member('B',100)},2) == 1, 'same member does not repeat join')
events = tracker:update({member('A',30),member('B',100)},4)
check(#events == 0, 'low health does not create text')
check(#tracker:update({member('A',20),member('B',100)},7) == 0, 'remaining low does not spam')
tracker:update({member('A',35),member('B',100)},8)
check(#tracker:update({member('A',29),member('B',100)},9) == 0, 'small heal does not rearm')
tracker:update({member('A',50),member('B',100)},10)
check(#tracker:update({member('A',20),member('B',100)},11) == 0, 'rapid repeat warning respects cooldown')
tracker:update({member('A',50),member('B',100)},24)
events = tracker:update({member('A',20),member('B',100)},25)
check(#events == 0, 'repeated low health stays text-free')
events = tracker:update({member('A',0),member('B',100)},28)
check(#events == 1 and events[1].kind == 'died', 'confirmed zero health alerts death')
check(#tracker:update({member('A',-5),member('B',100)},31) == 0, 'death is not repeated')
check(#tracker:update({member('B',100)},32,false,function() return false end) == 0, 'already dead member removed without repeat')
check(#tracker:update({},33,false,function() return false end) == 0, 'leaving is not treated as death')
tracker:update({member('C',100)},40)
events = tracker:update({},43,false,function(actor) return actor.key == 'C' end)
check(#events == 1 and events[1].kind == 'died', 'removed member only reported dead after health confirmation')
tracker:reset()
check(#tracker:update({member('D',10)},50) == 0, 'map change clears history and old alerts')
check(#tracker:update({member('D',nil)},51) == 0, 'unreadable health creates no false death or warning')
tracker:update({member('D',100)},52)
check(#tracker:update({member('D',0)},53,true) == 0, 'menu suppresses all alerts')
check(#tracker:update({member('D',0)},54) == 0, 'resume does not replay menu events')
local integrated = __alerts.new({AlertsEnabled=false,AlertJoined=false,AlertDeath=false,AlertLowHealth=false,AlertDuration=1})
integrated:update({},0)
check(integrated:update({member('A',100)},1)[1].kind == 'joined', 'legacy toggle does not disable integrated join alerts')
check(#integrated:update({member('A',20)},3) == 0, 'low health uses bar color, not text')
check(integrated:update({member('A',0)},5)[1].kind == 'died', 'death is included by default')
local bounded = __alerts.new({MaxAlerts=2})
bounded:update({},0)
check(#bounded:update({member('A',100),member('B',100),member('C',100)},1) == 2, 'burst is bounded instead of queuing stale notices')
local notice = {kind='joined',started=0,expires=5}
local opacity,offset = __alerts.visual(notice,0)
check(opacity > 0 and opacity < 1 and offset < 0, 'join starts with subtle fade and slide')
opacity,offset = __alerts.visual(notice,1)
check(opacity == 1 and offset == 0, 'join settles into stable readable position')
check(__alerts.visual(notice,4.8) < 1 and __alerts.visual(notice,5) == 0, 'notice fades out before expiry')
check(__alerts.healthOpacity(0.15,0.8) >= 0.65 and __alerts.healthOpacity(0.15,0.8) < 1, 'critical health gently pulses without disappearing')
check(__alerts.healthOpacity(0.2,0.8) == 1 and __alerts.healthOpacity(0,0.8) == 1, 'ordinary low health and dead bars do not pulse')
check(__alerts.visual({kind='died',started=0,expires=5},2) == 1, 'death emphasis stops after two brief cycles')
return count
